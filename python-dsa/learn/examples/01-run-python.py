# Lines that start with # are comments. Python skips them.
# They're notes for people reading the code.

print("Hello, Tanvi!")
print("This is my first Python program.")

# print can show numbers too. Python works out the maths first.
print(7)
print(2 + 3)

# Words go inside quotes. Numbers don't.
print("2 + 3")      # quotes: prints the text exactly as written
print(2 + 3)        # no quotes: prints the answer

# Give print several things, separated by commas.
# It puts a space between them.
print("I have", 3, "cats")

# print() with nothing inside prints an empty line.
print()
print("The end.")

